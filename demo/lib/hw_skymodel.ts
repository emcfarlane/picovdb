// Hosek-Wilkie Skylight Model 
// 
// An analytic model for full spectral sky-dome radiance

const SOLAR_RADIUS_RADIANS = 0.004450589; // 0.255 degrees

// Type Definitions
interface SkyState {
	params: Float32Array;        // 27 elements (9 * 3 for RGB)
	skyRadiances: Float32Array;  // 3 elements (RGB)
	solarRadiances: Float32Array; // 3 elements (RGB)
}

interface SkyParams {
	elevation: number;
	turbidity: number;
	albedo: [number, number, number]; // RGB tuple
}

/**
 * Evaluates a quintic Bezier curve with stride-9 data layout.
 * The C code uses pointer arithmetic (data + i) to step through interleaved data.
 * Here we pass the base offset explicitly.
 */
function quintic9(data: Float32Array, offset: number, t: number): number {
	const t2 = t * t;
	const t3 = t2 * t;
	const t4 = t2 * t2;
	const t5 = t4 * t;

	const invT = 1.0 - t;
	const invT2 = invT * invT;
	const invT3 = invT2 * invT;
	const invT4 = invT2 * invT2;
	const invT5 = invT4 * invT;

	// Stride of 9 between control points
	return (
		data[offset + 0 * 9] * invT5 +
		data[offset + 1 * 9] * 5.0 * invT4 * t +
		data[offset + 2 * 9] * 10.0 * invT3 * t2 +
		data[offset + 3 * 9] * 10.0 * invT2 * t3 +
		data[offset + 4 * 9] * 5.0 * invT * t4 +
		data[offset + 5 * 9] * t5
	);
}

/**
 * Evaluates a quintic Bezier curve with stride-1 (contiguous) data layout.
 */
function quintic1(data: Float32Array, offset: number, t: number): number {
	const t2 = t * t;
	const t3 = t2 * t;
	const t4 = t2 * t2;
	const t5 = t4 * t;

	const invT = 1.0 - t;
	const invT2 = invT * invT;
	const invT3 = invT2 * invT;
	const invT4 = invT2 * invT2;
	const invT5 = invT4 * invT;

	return (
		data[offset + 0] * invT5 +
		data[offset + 1] * 5.0 * invT4 * t +
		data[offset + 2] * 10.0 * invT3 * t2 +
		data[offset + 3] * 10.0 * invT2 * t3 +
		data[offset + 4] * 5.0 * invT * t4 +
		data[offset + 5] * t5
	);
}

/**
 * Initializes 9 sky model parameters by interpolating across turbidity and albedo.
 * 
 * @param outParams - Target array to write into
 * @param outOffset - Starting index in outParams
 * @param data - Source parameter data
 * @param turbidity - Atmospheric turbidity [1, 10]
 * @param albedo - Ground albedo [0, 1]
 * @param t - Elevation parameter (cube root normalized)
 */
function initParams(
	outParams: Float32Array,
	outOffset: number,
	data: Float32Array,
	turbidity: number,
	albedo: number,
	t: number
): void {
	const turbidityInt = Math.floor(turbidity);
	const turbidityRem = turbidity % 1.0;

	if (turbidityInt <= 0) {
		throw new RangeError("Turbidity must be greater than 0");
	}

	const turbidityMin = turbidityInt - 1;
	const turbidityMax = Math.min(turbidityInt, 9);

	// Offsets into the data array for the 4 interpolation corners
	// Layout: [albedo=0][turbidity 0-9] then [albedo=1][turbidity 0-9]
	// Each turbidity level has 6 control points * 9 parameters = 54 floats
	const p0Offset = 9 * 6 * turbidityMin;
	const p1Offset = 9 * 6 * turbidityMax;
	const p2Offset = 9 * 6 * 10 + 9 * 6 * turbidityMin;
	const p3Offset = 9 * 6 * 10 + 9 * 6 * turbidityMax;

	// Bilinear interpolation weights
	const s0 = (1.0 - albedo) * (1.0 - turbidityRem);
	const s1 = (1.0 - albedo) * turbidityRem;
	const s2 = albedo * (1.0 - turbidityRem);
	const s3 = albedo * turbidityRem;

	for (let i = 0; i < 9; i++) {
		outParams[outOffset + i] =
			s0 * quintic9(data, p0Offset + i, t) +
			s1 * quintic9(data, p1Offset + i, t) +
			s2 * quintic9(data, p2Offset + i, t) +
			s3 * quintic9(data, p3Offset + i, t);
	}
}

/**
 * Initializes sky radiance by interpolating across turbidity and albedo.
 */
function initSkyRadiance(
	outRadiance: Float32Array,
	outIndex: number,
	data: Float32Array,
	turbidity: number,
	albedo: number,
	t: number
): void {
	const turbidityInt = Math.floor(turbidity);
	const turbidityRem = turbidity % 1.0;

	if (turbidityInt <= 0) {
		throw new RangeError("Turbidity must be greater than 0");
	}

	const turbidityMin = turbidityInt - 1;
	const turbidityMax = Math.min(turbidityInt, 9);

	// 6 control points per turbidity level
	const p0Offset = 6 * turbidityMin;
	const p1Offset = 6 * turbidityMax;
	const p2Offset = 6 * 10 + 6 * turbidityMin;
	const p3Offset = 6 * 10 + 6 * turbidityMax;

	const s0 = (1.0 - albedo) * (1.0 - turbidityRem);
	const s1 = (1.0 - albedo) * turbidityRem;
	const s2 = albedo * (1.0 - turbidityRem);
	const s3 = albedo * turbidityRem;

	outRadiance[outIndex] =
		s0 * quintic1(data, p0Offset, t) +
		s1 * quintic1(data, p1Offset, t) +
		s2 * quintic1(data, p2Offset, t) +
		s3 * quintic1(data, p3Offset, t);
}

/**
 * Initializes solar radiance by linearly interpolating across turbidity.
 */
function initSolarRadiance(
	outRadiance: Float32Array,
	outIndex: number,
	data: Float32Array,
	turbidity: number
): void {
	const turbidityInt = Math.floor(turbidity);

	if (turbidityInt <= 0) {
		throw new RangeError("Turbidity must be greater than 0");
	}

	const turbidityRem = turbidity % 1.0;
	const turbidityMin = turbidityInt - 1;
	const turbidityMax = Math.min(turbidityInt, 9);

	outRadiance[outIndex] =
		data[turbidityMin] * (1.0 - turbidityRem) +
		data[turbidityMax] * turbidityRem;
}

/**
 * Creates a new sky state from the given parameters.
 */
export function createSkyState(params: SkyParams): SkyState {
	const { elevation, turbidity, albedo } = params;

	// Validation
	if (elevation < 0.0 || elevation > Math.PI) {
		throw new RangeError("Elevation must be in range [0, π]");
	}
	if (turbidity < 1.0 || turbidity > 10.0) {
		throw new RangeError("Turbidity must be in range [1, 10]");
	}
	if (albedo.some((a) => a < 0.0 || a > 1.0)) {
		throw new RangeError("Albedo components must be in range [0, 1]");
	}

	// Compute elevation parameter with perceptual scaling
	const t = Math.pow(elevation / (0.5 * Math.PI), 1.0 / 3.0);

	// Allocate state with typed arrays
	const state: SkyState = {
		params: new Float32Array(27),
		skyRadiances: new Float32Array(3),
		solarRadiances: new Float32Array(3),
	};

	// Initialize each color channel
	initParams(state.params, 0, params_r, turbidity, albedo[0], t);
	initParams(state.params, 9, params_g, turbidity, albedo[1], t);
	initParams(state.params, 18, params_b, turbidity, albedo[2], t);

	initSkyRadiance(state.skyRadiances, 0, radiances_r, turbidity, albedo[0], t);
	initSkyRadiance(state.skyRadiances, 1, radiances_g, turbidity, albedo[1], t);
	initSkyRadiance(state.skyRadiances, 2, radiances_b, turbidity, albedo[2], t);

	initSolarRadiance(state.solarRadiances, 0, solar_radiances_r, turbidity);
	initSolarRadiance(state.solarRadiances, 1, solar_radiances_g, turbidity);
	initSolarRadiance(state.solarRadiances, 2, solar_radiances_b, turbidity);

	return state;
}

export enum Channel {
	R = 0,
	G = 1,
	B = 2,
}

/**
 * Computes sky radiance for a given direction.
 * 
 * @param state - Precomputed sky state
 * @param theta - Zenith angle (0 = up, π/2 = horizon)
 * @param gamma - Angle between view direction and sun
 * @param channel - Color channel (R, G, or B)
 * @returns Radiance value
 */
export function skyStateRadiance(
	state: SkyState,
	theta: number,
	gamma: number,
	channel: Channel
): number {
	const channelIdx = channel as number;

	// Sky dome radiance
	const r = state.skyRadiances[channelIdx];
	const pBase = channelIdx * 9;
	const p0 = state.params[pBase + 0];
	const p1 = state.params[pBase + 1];
	const p2 = state.params[pBase + 2];
	const p3 = state.params[pBase + 3];
	const p4 = state.params[pBase + 4];
	const p5 = state.params[pBase + 5];
	const p6 = state.params[pBase + 6];
	const p7 = state.params[pBase + 7];
	const p8 = state.params[pBase + 8];

	const cosGamma = Math.cos(gamma);
	const cosGamma2 = cosGamma * cosGamma;
	const cosTheta = Math.abs(Math.cos(theta));

	const expM = Math.exp(p4 * gamma);
	const rayM = cosGamma2;
	const mieMlhs = 1.0 + cosGamma2;
	const mieMrhs = Math.pow(1.0 + p8 * p8 - 2.0 * p8 * cosGamma, 1.5);
	const mieM = mieMlhs / mieMrhs;
	const zenith = Math.sqrt(cosTheta);

	const radianceLhs = 1.0 + p0 * Math.exp(p1 / (cosTheta + 0.01));
	const radianceRhs = p2 + p3 * expM + p5 * rayM + p6 * mieM + p7 * zenith;
	const radianceDist = radianceLhs * radianceRhs;

	// Solar disk contribution
	const solarDiskRadius = gamma / SOLAR_RADIUS_RADIANS;
	const solarRadiance =
		solarDiskRadius <= 1.0 ? state.solarRadiances[channelIdx] : 0.0;

	return r * radianceDist + solarRadiance;
}

